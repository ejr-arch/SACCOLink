-- --- Final report queries ---
SELECT m.FULL_NAME, s.SCORE_VALUE, s.SCORE_BAND
  FROM CREDIT_SCORE s JOIN MEMBER m ON m.MEMBER_ID = s.MEMBER_ID
 WHERE s.IS_CURRENT = 'Y'
 ORDER BY s.SCORE_VALUE DESC;

SELECT m.FULL_NAME, COUNT(s.SAVINGS_ID) AS MONTHS_SAVED,
       NVL(SUM(s.AMOUNT_CONTRIBUTED), 0) AS TOTAL_SAVED
  FROM MEMBER m
  LEFT JOIN SAVINGS_RECORD s ON s.MEMBER_ID = m.MEMBER_ID
 GROUP BY m.FULL_NAME, m.MEMBER_ID
 ORDER BY MONTHS_SAVED DESC;

