-- --- Demo: generate + verify a passport for Grace, generate one for Sarah ---
DECLARE
    v_member_id NUMBER;
    v_pid       NUMBER;
    v_token     VARCHAR2(64);
    v_result    VARCHAR2(20);
    v_name      VARCHAR2(200);
    v_score     NUMBER;
    v_band      VARCHAR2(20);
    v_gen       TIMESTAMP;
    v_exp       TIMESTAMP;
BEGIN
    SELECT MEMBER_ID INTO v_member_id FROM MEMBER WHERE FULL_NAME = 'Grace Namukasa';
    SP_GENERATE_PASSPORT(p_member_id   => v_member_id,
                         p_passport_id => v_pid,
                         p_qr_token    => v_token);
    DBMS_OUTPUT.PUT_LINE('Passport ' || v_pid || ' generated, token = ' || v_token);

    v_result := FN_VERIFY_PASSPORT(v_token, v_name, v_score, v_band, v_gen, v_exp);
    DBMS_OUTPUT.PUT_LINE('Verify result: ' || v_result || ' | ' || v_name ||
                         ' | Score: ' || v_score || ' (' || v_band || ')');

    SELECT MEMBER_ID INTO v_member_id FROM MEMBER WHERE FULL_NAME = 'Sarah Kintu';
    SP_GENERATE_PASSPORT(p_member_id   => v_member_id,
                         p_passport_id => v_pid,
                         p_qr_token    => v_token);
    DBMS_OUTPUT.PUT_LINE('Passport ' || v_pid || ' generated for Sarah Kintu, token = ' || v_token);
END;
