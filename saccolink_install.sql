-- 6. VIEWS
-- The V_PASSPORT_DETAIL view hides the three-table join from reporting code.
-- ----------------------------------------------------------------------------
PROMPT -- 6. Querying a VIEW
SELECT FULL_NAME, SCORE_BAND, PASSPORT_STATUS
  FROM V_PASSPORT_DETAIL
 WHERE SCORE_BAND = 'EXCELLENT';

