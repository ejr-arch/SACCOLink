CREATE OR REPLACE TRIGGER TRG_MEMBER_BI
BEFORE INSERT ON MEMBER
FOR EACH ROW
WHEN (NEW.MEMBER_ID IS NULL)
BEGIN
    :NEW.MEMBER_ID := SEQ_MEMBER.NEXTVAL;
END TRG_MEMBER_BI;
/

